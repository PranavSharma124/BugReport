import type { BugReport } from "../types/bug-report";

/**
 * Escape pipe characters in table cells; used if we ever embed tables.
 * For general field content we wrap in a code block only when the user
 * included backticks, to avoid breaking fenced-block syntax.
 */
function safeField(value: string, placeholder = "_Not provided_"): string {
  return value.trim() || placeholder;
}

/**
 * Generate a Markdown string from a BugReport.
 *
 * - Always uses the *current* report, not original captured context.
 * - Handles empty fields gracefully with placeholders.
 * - Formats reproduction steps as a numbered list.
 */
export function generateMarkdown(report: BugReport): string {
  const steps =
    report.reproductionSteps.filter((s) => s.trim()).length > 0
      ? report.reproductionSteps
          .filter((s) => s.trim())
          .map((s, i) => `${i + 1}. ${s.trim()}`)
          .join("\n")
      : "_No reproduction steps provided._";

  const lines: string[] = [
    `# Bug Report: ${safeField(report.title, "Untitled Bug")}`,
    "",
    `**Source URL:** ${safeField(report.sourceUrl, "_No URL provided_")}`,
    "",
    "## Summary",
    "",
    safeField(report.summary),
    "",
    "## Evidence",
    "",
    safeField(report.evidence),
    "",
    "## Steps to Reproduce",
    "",
    steps,
    "",
    "## Expected Behavior",
    "",
    safeField(report.expectedBehavior),
    "",
    "## Actual Behavior",
    "",
    safeField(report.actualBehavior),
    "",
    "---",
    "",
    `_Generated by BugLens — review before sharing._`,
  ];

  return lines.join("\n");
}

/**
 * Derive a safe filename from the bug title.
 * Falls back to "bug-report" if the title is empty.
 */
export function markdownFilename(report: BugReport): string {
  const slug = report.title
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return `${slug || "bug-report"}.md`;
}

/**
 * Copy Markdown to clipboard.
 * Returns { success: true } or { success: false, error: string }.
 * Does NOT silently swallow errors.
 */
export async function copyMarkdown(
  report: BugReport
): Promise<{ success: boolean; error?: string }> {
  const md = generateMarkdown(report);
  try {
    await navigator.clipboard.writeText(md);
    return { success: true };
  } catch (err) {
    const message =
      err instanceof Error ? err.message : "Clipboard write failed.";
    return { success: false, error: message };
  }
}

/**
 * Trigger a browser download of the Markdown file.
 * Returns { success: true } or { success: false, error: string }.
 */
export function downloadMarkdown(
  report: BugReport
): { success: boolean; error?: string } {
  try {
    const md = generateMarkdown(report);
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = markdownFilename(report);
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
    return { success: true };
  } catch (err) {
    const message =
      err instanceof Error ? err.message : "Download failed.";
    return { success: false, error: message };
  }
}
